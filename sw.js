self.addEventListener('install', (e) => {
  e.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // addAll is all-or-nothing; add one at a time so a single bad path
    // can't leave the app with no offline cache at all
    await Promise.all(ASSETS.map(async (url) => {
      try { await cache.add(new Request(url, { cache: 'reload' })); }
      catch (err) { console.warn('[sw] could not precache', url, err); }
    }));
    self.skipWaiting();
  })());
});

self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(k => k !== CACHE && k.startsWith('fj-')).map(k => caches.delete(k)));
    await self.clients.claim();
    const clients = await self.clients.matchAll({ type: 'window' });
    clients.forEach(c => c.postMessage({ type: 'sw-updated', version: VERSION }));
  })());
});

self.addEventListener('message', (e) => {
  if (e.data && e.data.type === 'skip-waiting') self.skipWaiting();
  // The app tells the worker what the badge should say when it opens or
  // closes, because the count lives in the database, not in here.
  if (e.data && e.data.type === 'badge') setBadge(e.data.count);
});

/* ============================================================
   PUSH. What arrives when the app is closed.

   iOS delivers this only to an app that has been added to the home
   screen and has been granted permission. Everywhere else it is the
   ordinary Web Push contract.

   TWO THINGS HAPPEN, AND THE ORDER MATTERS. The notification is shown
   first, because iOS terminates a push handler that resolves without
   showing one, and repeated offences stop delivery to the app
   altogether. The badge is second, and is allowed to fail.
   ============================================================ */
function setBadge(n) {
  try {
    if (!('setAppBadge' in self.navigator)) return;
    if (n > 0) self.navigator.setAppBadge(n); else self.navigator.clearAppBadge();
  } catch (err) { /* unsupported, or denied. Never worth failing over. */ }
}

self.addEventListener('push', (e) => {
  /* A push with no readable payload is still a push, and still has to
     show something. Silent failure here is the one thing iOS punishes. */
  let d = {};
  try { d = e.data ? e.data.json() : {}; } catch (err) {
    try { d = { body: e.data ? e.data.text() : '' }; } catch (err2) { d = {}; }
  }
  const title = d.title || 'Fitness Journey';
  const body  = d.body  || 'Something new from your coach.';
  const url   = d.url   || './index.html';

  e.waitUntil((async () => {
    await self.registration.showNotification(title, {
      body,
      icon: './icon-192.png',
      badge: './icon-192.png',
      // Same tag replaces rather than stacks, so a coach saving twice
      // does not leave two identical notifications on the lock screen.
      tag: d.tag || 'fj',
      renotify: true,
      data: { url },
    });
    setBadge(typeof d.count === 'number' ? d.count : 1);
  })());
});

self.addEventListener('notificationclick', (e) => {
  e.notification.close();
  const url = (e.notification.data && e.notification.data.url) || './index.html';
  e.waitUntil((async () => {
    const all = await clients.matchAll({ type: 'window', includeUncontrolled: true });
    /* Focus the app if it is already open rather than opening a second
       copy of it. A person who taps a notification expects to land in
       the app they already have, not a new one beside it. */
    for (const c of all) {
      if (c.url.includes(self.location.origin)) {
        await c.focus();
        if ('navigate' in c) { try { await c.navigate(url); } catch (err) { /* same page */ } }
        return;
      }
    }
    await clients.openWindow(url);
  })());
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;      // never touch third-party requests
  // ?live = "what is on the site right now" (the update check, js/update-banner.js): never from cache
  if (url.searchParams.has('live')) return;

  // a navigation (opening the app, or a refresh) must always resolve,
  // connection or not — that is what makes it feel like an installed app
  if (req.mode === 'navigate') {
    e.respondWith((async () => {
      // WHICH PAGE IS THIS, ACTUALLY. Every page in this app is a navigation:
      // dashboard.html, coach.html, onboarding.html. This used to write the
      // response into './index.html' whatever had been asked for, so opening
      // the console once left the console's HTML cached as the app's start
      // page - and the next offline open of the home-screen icon served it.
      // Cache each page under its own name, and only the real start page
      // under index.html.
      const path = url.pathname.split('/').pop() || 'index.html';
      const key = './' + path;
      try {
        const fresh = await fetch(req);
        const cache = await caches.open(CACHE);
        // Only cache pages the shell actually ships; a navigation to
        // anything else is not ours to keep.
        if (ASSETS.includes(key)) cache.put(key, fresh.clone());
        return fresh;
      } catch (err) {
        const cache = await caches.open(CACHE);
        // Offline: the page asked for, then the start page. A workout must
        // open from the home screen with no signal, which is the fallback -
        // but not at the cost of serving the wrong page when we have it.
        return (await cache.match(key))
            || (await cache.match('./index.html'))
            || Response.error();
      }
    })());
    return;
  }

  e.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    try {
      const fresh = await fetch(req);
      if (fresh && fresh.ok && fresh.type === 'basic') cache.put(req, fresh.clone());
      return fresh;
    } catch (err) {
      return new Response('', { status: 504, statusText: 'offline' });
    }
  })());
});
